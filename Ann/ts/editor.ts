//Debugger Start
const Debugger = document.getElementById("debugger")!;

let glInfo = null;

function updateDebugger() {
  glInfo = engine.getGlInfo();
  
  Debugger.innerHTML = `
    <div class="debugger-top">
      <div class="performance">
        <div class="label">Performance</div>
        <div style="display: inline-block;" class="value">${Math.round(engine.getFps())} fps</div>
        <div class="value">∆ ${frameDelta.toFixed(2)}ms</div>
      </div>
      
      <button id="debugger-close">×</button>
    </div>
    
    <div class="debugger-body">
      <div class="GPU">
        <div class="label">GPU</div>
        <div class="value">${glInfo.vendor}</div>
        <div class="value">${glInfo.renderer}</div>
      </div>
      <div class="API">
        <div class="label">API</div>
        <div class="value">${glInfo.version}</div>
      </div>
    </div>
  `;
}

console.log(engine.getGlInfo());

Debugger.addEventListener("click", (event) => {
  const target = event.target as HTMLElement;

  if (target.closest("#debugger-close")) {
    hideDebugger();
  }
});

let debugUpdateIntervalId: number | undefined = undefined;

function showDebugger() {
  updateDebugger();

  if (debugUpdateIntervalId !== undefined) {
    clearInterval(debugUpdateIntervalId);
  }

  debugUpdateIntervalId = setInterval(updateDebugger, 150);
  
  gsap.fromTo("#debugger", {
    opacity: 0,
    scale: 0
  }, {
    opacity: 1,
    scale: 1,
    duration: 0.7,
    ease: "power4.inOut"
  });
}

function hideDebugger() {
  if (debugUpdateIntervalId !== undefined) {
    clearInterval(debugUpdateIntervalId);
    debugUpdateIntervalId = undefined;
  }
  
  gsap.fromTo("#debugger", {
    opacity: 1,
    scale: 1
  }, {
    opacity: 0,
    scale: 0,
    duration: 0.7,
    ease: "power4.inOut"
  });
}

setTimeout(showDebugger, 1000);
