let neuronId = 1;
let synapseId = 1000;
let batchId = 1;

const neuronPos = new Map<number, Float32Array>();

const spacing = 2.5;

// ===================================================
// Helper to create a centered layer
// ===================================================

function createLayer(
  centerX: number,
  centerY: number,
  centerZ: number,
  rows: number,
  cols: number,
  depth: number
): LayerData {

  const ids: number[] = [];

  const corner = new Float32Array([
    centerX - ((rows - 1) * spacing) / 2,
    centerY - ((cols - 1) * spacing) / 2,
    centerZ - ((depth - 1) * spacing) / 2
  ]);

  for (let i = 0; i < rows; i++) {
    for (let j = 0; j < cols; j++) {
      for (let k = 0; k < depth; k++) {

        const id = neuronId++;

        ids.push(id);

        neuronPos.set(
          id,
          new Float32Array([
            corner[0] + i * spacing,
            corner[1] + j * spacing,
            corner[2] + k * spacing
          ])
        );
      }
    }
  }

  return {
    id: batchId++,
    pos: corner,
    shape: new Uint32Array([rows, cols, depth]),
    ids: new Float64Array(ids)
  };
}

// ===================================================
// Layers
// ===================================================

const layer0 = createLayer(
  0,   // center x
  0,   // center y
  0,   // center z
  1, 8, 8
);

const layer1 = createLayer(
  25,
  0,
  0,
  1, 4, 4
);

const layer2 = createLayer(
  50,
  0,
  0,
  1, 3, 3
);

net.newLayer(layer0, spacing);
net.newLayer(layer1, spacing);
net.newLayer(layer2, spacing);

// ===================================================
// Fully connected synapse batches
// ===================================================

function connectLayersBatch(
  from: LayerData,
  to: LayerData
): SynapseBatchData {

  const ids: number[] = [];
  const fts: number[][] = [];

  for (const startId of from.ids) {

    const startPos = neuronPos.get(startId)!;

    for (const endId of to.ids) {

      const endPos = neuronPos.get(endId)!;

      ids.push(synapseId++);

      fts.push([
        startPos[0], startPos[1], startPos[2],
        endPos[0],   endPos[1],   endPos[2]
      ]);
    }
  }

  return {
    id: batchId++,
    ids: new Float64Array(ids),
    fts
  };
}

net.newSynapseBatch(connectLayersBatch(layer0, layer1));
net.newSynapseBatch(connectLayersBatch(layer1, layer2));
