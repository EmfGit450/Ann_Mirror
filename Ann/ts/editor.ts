//Init Start
let engine: WebGPUEngine | Engine | null = null;

async function createEngine(canvas: HTMLCanvasElement) {
  if ("gpu" in navigator) {
    try {
      const webgpuEngine = new WebGPUEngine(canvas);

      await webgpuEngine.initAsync();

      console.log("Ann - Using WebGPU");
      return webgpuEngine;
    } catch (error) {
      console.warn("Ann - WebGPU initialization failed; falling back to WebGL", error);
    }
  }

  console.log("Ann - Using WebGL");
  return new Engine(canvas, true);
}

async function getWebGPUInfo() {
  if (!navigator.gpu) {
    return null;
  }

  const adapter = await navigator.gpu.requestAdapter();

  if (!adapter) {
    return null;
  }

  const info = adapter.info;

  return {
    vendor: info.vendor || "Unavailable",
    renderer: info.device || info.description || "Unavailable",
  };
}

async function getGraphicsInfo() {
  if (engine.isWebGPU) {
    const info = await getWebGPUInfo();

    return {
      api: "WebGPU",
      vendor: info?.vendor ?? "Unavailable",
      renderer: info?.renderer ?? "Unavailable"
    };
  }

  const info = engine.getGlInfo();

  return {
    api: `WebGL ${engine.webGLVersion}`,
    vendor: info.vendor,
    renderer: info.renderer
  };
}
//Init End

//Debugger Start
const Debugger = document.getElementById("debugger")!;
  
let hardwareInfo = null;
let debugUpdateIntervalId: number | undefined = undefined;
let frameDelta: number | null = null;

async function updateDebugger() {
  hardwareInfo = await getGraphicsInfo();
  
  Debugger.innerHTML = `
    <div class="debugger-top">
      <div class="performance">
        <div class="label">Performance</div>
        <div style="display: inline-block;" class="value">${Math.round(engine.getFps())} fps</div>
        <div class="value">∆ ${frameDelta.toFixed(2)}ms</div>
      </div>
      
      <button id="debugger-close">×</button>
    </div>
    
    <div class="debugger-body">
      <div class="Vendor">
        <div class="label">Vendor</div>
        <div class="value">${hardwareInfo.vendor}</div>
      </div>
      
      <div class="Renderer">
        <div class="label">Renderer</div>
        <div class="value">${hardwareInfo.renderer}</div>
      </div>
      
      <div class="API">
        <div class="label">API</div>
        <div class="value">${hardwareInfo.api}</div>
      </div>
    </div>
  `;
}

function showDebugger() {
  updateDebugger();

  if (debugUpdateIntervalId !== undefined) {
    clearInterval(debugUpdateIntervalId);
  }

  debugUpdateIntervalId = setInterval(updateDebugger, 150);
  
  gsap.fromTo("#debugger", {
    opacity: 0,
    scale: 0
  }, {
    opacity: 1,
    scale: 1,
    duration: 0.7,
    ease: "power4.inOut"
  });
}

function hideDebugger() {
  if (debugUpdateIntervalId !== undefined) {
    clearInterval(debugUpdateIntervalId);
    debugUpdateIntervalId = undefined;
  }
  
  gsap.fromTo("#debugger", {
    opacity: 1,
    scale: 1
  }, {
    opacity: 0,
    scale: 0,
    duration: 0.7,
    ease: "power4.inOut"
  });
}
//Debugger End

async function Main() {
  const canvas = document.getElementById("mainCanvas") as HTMLCanvasElement;
  engine = await createEngine(canvas);
  const scene = new Scene(engine);
  
  scene.clearColor = new Color4(0.01, 0.01, 0.01, 1);
  
  if (!engine.isWebGPU) console.warn("This website requires WebGPU for functionality");
  
  new HemisphericLight("light", new Vector3(0, 80, 0), scene);
  
  //Tests Start (Generated by AI for quick testing)
  const net = new Network(scene);
  
  const layer0: LayerData = {
    id: 1,
    pos: [0, 0, 0],
    shape: [1, 14, 14],
    ids: undefined
  };

  const layer1: LayerData = {
    id: 2,
    pos: [20, 0, 0],
    shape: [1, 4, 4],
    ids: undefined
  };

  const layer2: LayerData = {
    id: 3,
    pos: [40, 0, 0],
    shape: [1, 4, 4],
    ids: undefined
  };

  const layer3: LayerData = {
    id: 4,
    pos: [60, 0, 0],
    shape: [1, 10, 1],
    ids: undefined
  };

  net.newLayer(layer0);
  net.newLayer(layer1);
  net.newLayer(layer2);
  net.newLayer(layer3);

  net.newDenseSynapseBatch(1, 2, 11, undefined);
  net.newDenseSynapseBatch(2, 3, 12, undefined);
  net.newDenseSynapseBatch(3, 4, 13, undefined);
  //Tests End

  const camera = new Camera({scene: scene, canvas: canvas});

  engine.runRenderLoop(() => {
    scene.render(); 
  });

  let lastFrameTime = performance.now();

  scene.onBeforeRenderObservable.add(() => {
    const now = performance.now();
    frameDelta = now - lastFrameTime;
    lastFrameTime = now;
  });

  //Debugger Start
  Debugger.addEventListener("click", (event) => {
    const target = event.target as HTMLElement;
    
    if (target.closest("#debugger-close")) {
      hideDebugger();
    }
  });
  
  setTimeout(showDebugger, 1000);
  //setTimeout(hideDebugger, 8000);

  //@ts-ignore
  window.net = () => net;
  //Debugger End

  window.addEventListener("resize", () => {
    engine.resize();
  });
}
Main();