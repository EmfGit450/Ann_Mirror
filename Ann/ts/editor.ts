// ===================================================
// Generate Fully Connected Synapse Batches
// ===================================================

function connectLayersBatch(fromLayer: number[], toLayer: number[]): SynapseBatchData {
  const ids: number[] = [];
  const fts: number[][] = [];

  for (const startId of fromLayer) {
    const startPos = neuronPos.get(startId)!;
    for (const endId of toLayer) {
      const endPos = neuronPos.get(endId)!;
      ids.push(synapseId++);

      fts.push([
        startPos[0], startPos[1], startPos[2],
        endPos[0],   endPos[1],   endPos[2]
      ]);
    }
  }

  return {
    id: batchId++,
    ids: new Float64Array(ids),
    fts
  };
}

