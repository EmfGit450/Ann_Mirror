import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";

import { Camera } from "./camera";

import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color4 } from "@babylonjs/core/Maths/math.color";

import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";

import { randInt53 } from "./structure";
import { Network, LayerData, SynapseBatchData } from "./structure";

import "@babylonjs/core/Meshes/instancedMesh";

const canvas = document.getElementById("mainCanvas") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);

scene.clearColor = new Color4(0.01, 0.01, 0.01, 1);

if (!engine.isWebGPU) console.warn("This website requires WebGPU for functionality");

new HemisphericLight("light", new Vector3(0, 80, 0), scene);

//Tests Start (Generated by AI for quick testing)
const net = new Network(scene);

const layer0: LayerData = {
  id: 1,
  pos: new Float32Array([0, 0, 0]),
  shape: new Uint32Array([1, 65, 65]),
  ids: new Float64Array(4225)
};

const layer1: LayerData = {
  id: 2,
  pos: new Float32Array([40, 0, 0]),
  shape: new Uint32Array([1, 10, 10]),
  ids: new Float64Array(100)
};

const layer2: LayerData = {
  id: 3,
  pos: new Float32Array([70, 0, 0]),
  shape: new Uint32Array([1, 4, 4]),
  ids: new Float64Array(16)
};

const layer3: LayerData = {
  id: 4,
  pos: new Float32Array([95, 0, 0]),
  shape: new Uint32Array([1, 10, 1]),
  ids: new Float64Array(10)
};

net.newLayer(layer0);
net.newLayer(layer1);
net.newLayer(layer2);
net.newLayer(layer3);

net.newDenseSynapseBatch(layer0, layer1);
net.newDenseSynapseBatch(layer1, layer2);
net.newDenseSynapseBatch(layer2, layer3);
//Tests End
//Tests End

const camera = new Camera({scene: scene, canvas: canvas});

engine.runRenderLoop(() => {
  scene.render();
});

